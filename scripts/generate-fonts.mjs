/** Reproduce app font assets. Normal builds never download fonts. */
import { format } from "prettier";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}/scripts/fonts/manifest.json`, "utf8"));
mkdirSync(`${root}/public/fonts`, { recursive: true });
for (const file of manifest.files) {
  const path = `${root}/public/fonts/${file.file}`;
  let bytes;
  if (process.argv.includes("--download")) {
    const response = await fetch(file.url, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Font download failed: ${file.file} (${response.status})`);
    bytes = Buffer.from(await response.arrayBuffer());
  } else bytes = readFileSync(path);
  if (createHash("sha256").update(bytes).digest("hex") !== file.sha256)
    throw new Error(`Font checksum mismatch: ${file.file}`);
  if (bytes.length !== file.bytes) throw new Error(`Font size mismatch: ${file.file}`);
  if (process.argv.includes("--download")) writeFileSync(path, bytes);
}
const css =
  "/* Generated by scripts/generate-fonts.mjs. Licences: public/fonts/*-OFL.txt. */\n" +
  manifest.faces
    .map(
      (face) =>
        `@font-face {\n  font-family: "${face.family}";\n  font-style: normal;\n  font-weight: ${face.weight};\n  font-display: swap;\n  src: url("/fonts/${face.file}") format("woff2");\n  unicode-range: ${face.unicodeRange};\n}\n`,
    )
    .join("\n");
writeFileSync(`${root}/src/styles/fonts.css`, await format(css, { parser: "css" }));
console.log(`Verified ${manifest.files.length} font/licence files and generated local font faces.`);
